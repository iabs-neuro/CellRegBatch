function cfg = batch_default_config()
%BATCH_DEFAULT_CONFIG Default parameters for the batch CellReg wrapper.
    cfg = struct();
    cfg.version = 1;

    cfg.cellreg = struct( ...
        'microns_per_pixel', 1.6, ...
        'alignment_type', 'Translations', ...
        'maximal_rotation', 5, ...
        'reference_session_index', 1, ...
        'maximal_distance_um', 15, ... % at 50 the spatial-correlation model collapses on dense FOVs (HOS, 42 mice)
        'registration_approach', 'Probabilistic', ...
        'initial_registration_type', 'auto', ...
        'use_parallel_processing', true, ...
        'figures_visibility', 'off', ...
        'write_to_file', true, ...
        'alignment_min_xcorr', 0.2, ...
        'expected_n_sessions', 5, ...
        'rotation_fallback_deg', 90, ...
        'nonrigid_smoothness', 2);

    cfg.p_same_tuning = struct('fpr_max', 0.03);

    cfg.anomaly_thresholds = struct( ...
        'z_threshold', 2.0, ...
        'max_translation_px', 30, ...
        'min_xcorr', 0.3, ...
        'max_mse', 0.1);

    cfg.io = struct( ...
        'input_folder', '', ...
        'output_subfolder_name', 'Matching');
end

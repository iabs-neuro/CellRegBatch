function cfg = batch_default_config()
%BATCH_DEFAULT_CONFIG Default parameters for the batch CellReg wrapper.
    cfg = struct();
    cfg.version = 2;

    cfg.cellreg = struct( ...
        'microns_per_pixel', 1.6, ...
        'alignment_type', 'Translations', ...
        'maximal_rotation', 5, ...
        'reference_session_index', 1, ...
        'maximal_distance_um', 15, ... % at 50 the spatial-correlation model collapses on dense FOVs (HOS, 42 mice)
        'registration_approach', 'Probabilistic', ...
        'initial_registration_type', 'auto', ... % 'auto' = the model with the better fit
        'use_parallel_processing', true, ...
        'figures_visibility', 'off', ...
        'write_to_file', true, ...
        'alignment_min_xcorr', 0.2, ...
        'expected_n_sessions', 5, ...
        'rotation_fallback_deg', 90, ...
        'nonrigid_smoothness', 2);

    cfg.p_same_tuning = struct('fpr_max', 0.03);

    % Calibrated on 83 lab datasets (HOS, LNOF, LT1, 2026-10): the red
    % flags there are the mice the lab excluded, sparse mice, and one
    % mouse with a session that lost two thirds of its cells.
    cfg.anomaly_thresholds = struct( ...
        'few_cells_red', 30, ...     % median cells per session
        'few_cells_yellow', 60, ...
        'cell_drop_red', 0.4, ...    % worst session / median session
        'cell_drop_yellow', 0.6, ...
        'xcorr_red', 0.25, ...       % lowest alignment cross-correlation
        'xcorr_yellow', 0.3, ...
        'shift_yellow_px', 30, ...   % largest alignment shift
        'mse_red', 0.15, ...         % model fit error (MSE)
        'mse_yellow', 0.1, ...
        'match_z_red', 3, ...        % robust z below the batch median
        'match_z_yellow', 2, ...
        'session_link_red', 0.4, ... % worst session's linked share / median
        'session_link_yellow', 0.6);

    cfg.io = struct( ...
        'input_folder', '', ...
        'output_subfolder_name', 'Matching');
end

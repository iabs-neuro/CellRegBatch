function m = parameter_info()
%PARAMETER_INFO Help text for the "?" buttons of the GUI.
%   Keys are config paths (as in batch_default_config) or topic names
%   ('input_folder', 'warnings', 'results_table').
    m = containers.Map('KeyType', 'char', 'ValueType', 'char');

    m('input_folder') = sprintf(['Put the files of all mice in one folder.\n\n' ...
        'Name each file <EXPERIMENT>_<MOUSE>_<SESSION>.mat, for example ' ...
        'HOS_F01_1D.mat. Each part has letters and digits only, any number of ' ...
        'them; _ separates the parts. A trial part _<number>T belongs to the ' ...
        'session (1D_2T). Anything after it, from the next _, is ignored ' ...
        '(HOS_F01_1D_filters.mat).\n\n' ...
        'Scan groups the files into datasets (one per mouse) and sorts the ' ...
        'sessions by name, numbers by value (2D before 10D). Results go to the ' ...
        'subfolder Matching; the names of the batch files start with the ' ...
        'experiment name (HOS_batch_results.csv).']);
    m('cellreg.expected_n_sessions') = sprintf(['How many sessions each mouse ' ...
        'should have in this experiment.\n\nA dataset with another number of ' ...
        'sessions is still matched, but it gets a red "Sessions" warning. If it ' ...
        'has fewer sessions, its cell map has a column of zeros for each missing ' ...
        'session, so all cell maps of the batch have this number of columns. The ' ...
        'column names are the most common session names among the mice with ' ...
        'this number of sessions.\n\nThe Check column of the table shows which datasets do ' ...
        'not match this number.']);

    m('cellreg.microns_per_pixel') = sprintf(['Size of one image pixel in micrometres. ' ...
        'Take it from your microscope settings. It converts distances (maximal ' ...
        'distance, centroid distances) from micrometres to pixels.']);
    m('cellreg.alignment_type') = sprintf(['How CellReg aligns each session to the ' ...
        'reference session.\n\nTranslations: shifts only (default, fastest).\n' ...
        'Translations and Rotations: shifts and rotation up to "Maximal rotation".\n' ...
        'Non-rigid: local deformations.\n\nIf the chosen mode fails, the batch tries ' ...
        'the next one: rotations, large rotations, then non-rigid.']);
    m('cellreg.maximal_rotation') = sprintf(['Largest rotation (degrees) that the ' ...
        '"Translations and Rotations" mode searches.']);
    m('cellreg.reference_session_index') = sprintf(['Number of the session that the ' ...
        'other sessions are aligned to (1 = the first session in name order).']);
    m('cellreg.maximal_distance_um') = sprintf(['Largest distance (micrometres) ' ...
        'between two cell centroids that can still be the same cell. 15 suits dense ' ...
        'one-photon recordings; at 50 the spatial-correlation model fails on dense ' ...
        'fields of view.']);
    m('cellreg.registration_approach') = sprintf(['The batch uses the probabilistic ' ...
        'approach of CellReg only. This field is fixed.']);
    m('cellreg.initial_registration_type') = sprintf(['Which CellReg model gives the ' ...
        'probability that two cells are the same cell.\n\nauto: the model with the ' ...
        'better fit, as the CellReg GUI suggests (default).\nSpatial correlation: ' ...
        'similarity of the footprints.\nCentroid distance: distance between the ' ...
        'centres.\n\nSet a model to use it for every dataset of the batch.']);
    m('cellreg.alignment_min_xcorr') = sprintf(['If the alignment cross-correlation ' ...
        'of any session is below this value, the batch tries the next alignment mode. ' ...
        'If no mode passes, the best one is used and the dataset gets a red ' ...
        '"Alignment" warning.']);
    m('p_same_tuning.fpr_max') = sprintf(['Largest allowed fraction of false ' ...
        'positives (FPR).\n\nThe batch starts at P_same = 0.5. If the FPR there is ' ...
        'higher than this value, it raises P_same until the FPR is low enough, up to ' ...
        '0.95. If 0.95 is still not enough, the dataset gets a red "Model fit" warning.']);
    m('cellreg.write_to_file') = sprintf(['Save the cellRegistered_*.mat file, the ' ...
        'CellReg log and the cell map of each dataset. Turn off only for a dry run.']);
    m('cellreg.figures_visibility') = sprintf(['off: CellReg figures are saved but ' ...
        'not shown (recommended for a batch). on: every figure opens on screen.']);
    m('cellreg.use_parallel_processing') = sprintf(['Use the Parallel Computing ' ...
        'Toolbox to speed up the alignment. Without the toolbox, turn it off.']);

    m('anomaly_thresholds.few_cells_yellow') = sprintf(['Few cells: the median ' ...
        'number of cells per session.\n\nBelow "yellow": yellow warning. Below ' ...
        '"red": red warning.\n\nWith few cells the model and the match statistics ' ...
        'are less reliable.']);
    m('anomaly_thresholds.cell_drop_yellow') = sprintf(['Cell drop: cells in the ' ...
        'worst session divided by the median session of the same dataset (0 to 1).' ...
        '\n\nBelow "yellow": yellow warning. Below "red": red warning.\n\nA low ' ...
        'value means one session lost many cells: check its recording and curation.']);
    m('anomaly_thresholds.xcorr_yellow') = sprintf(['Alignment: the lowest ' ...
        'cross-correlation between a session and the reference session after ' ...
        'alignment.\n\nBelow "yellow": yellow warning. Below "red": red warning.' ...
        '\n\nA low value means a session does not look like the reference.']);
    m('anomaly_thresholds.shift_yellow_px') = sprintf(['Alignment: the largest shift ' ...
        '(pixels) of a session relative to the reference.\n\nAbove this value: yellow ' ...
        'warning. A large shift can be correct, but less of the field of view ' ...
        'overlaps, so fewer cells can match.']);
    m('anomaly_thresholds.mse_yellow') = sprintf(['Model fit: the error (MSE) of the ' ...
        'probabilistic model fit.\n\nAbove "yellow": yellow warning. Above "red": red ' ...
        'warning.\n\nIn 83 lab datasets good fits had MSE 0.05 to 0.1. Sparse mice can ' ...
        'have a high MSE from noise alone.']);
    m('anomaly_thresholds.match_z_yellow') = sprintf(['Low match: how far the match %% ' ...
        '(cells in all sessions / mean cells per session) is below the median of the ' ...
        'batch, in robust standard deviations (MAD-based z).\n\nFurther than "yellow": ' ...
        'yellow warning. Further than "red": red warning.\n\nThe comparison needs at ' ...
        'least 5 datasets with the expected number of sessions. A dataset with no ' ...
        'cell in all sessions is always red.']);

    m('anomaly_thresholds.session_link_yellow') = sprintf(['Low match: for each ' ...
        'session, the share of its cells that are found in at least one other session. ' ...
        'The rule divides the worst session''s share by the median share of the dataset ' ...
        '(0 to 1).\n\nBelow "yellow": yellow warning. Below "red": red warning.\n\nA low ' ...
        'value means one session hardly connects to the others: it is usually misaligned ' ...
        'or shows another field of view. Needs 3 or more sessions; works in a batch of ' ...
        'any size.']);
    m('warnings') = sprintf(['Each dataset gets six warnings. Grey: no problem. ' ...
        'Yellow: check it. Red: a problem.\n\n' ...
        'Sessions: the session count differs from "Expected sessions".\n' ...
        'Few cells: few cells per session.\n' ...
        'Cell drop: one session has far fewer cells than the others.\n' ...
        'Alignment: a session does not match the reference, or it moved a lot.\n' ...
        'Model fit: the probabilistic model fits poorly.\n' ...
        'Low match: few cells are found in all sessions, or one session hardly connects ' ...
        'to the others.\n\n' ...
        'Click a cell of the table to see the rule and the value. All details are in ' ...
        '<EXPERIMENT>_batch_warnings_detail.csv; the picture is ' ...
        '<EXPERIMENT>_batch_warnings.png.']);
end
